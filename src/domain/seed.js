function items(prefix, rows) {
  return rows.map((row, index) => ({
    id: `${prefix}-i${index}`,
    description: row[0],
    qty: row[1],
    unit: row[2],
    unitCost: row[3],
  }))
}

function poItems(prefix, request) {
  return request.items.map((item) => ({
    ...item,
    id: `${prefix}-${item.id}`,
    amount: item.qty * item.unitCost,
  }))
}

function level(role, status, actorId = null, comment = '', at = null, designatedUserId = null) {
  return { role, designatedUserId, status, actorId, comment, at }
}

function hist(id, at, actorId, action, comment = '') {
  return { id, at, actorId, action, comment }
}

